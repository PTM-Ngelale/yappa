// Turns the reviewed scripts/words/review/words.review.json into the next migration, which
// fills in each word's difficulty, forbidden list, components and variants. Run it only
// after a person has checked the file: it is what ships to players.
//
// Run: node scripts/words/to-sql.mjs
//
// Refuses (and lists why) if any entry is malformed or still has a "check" note: delete the
// note once you've fixed or accepted that word.
import fs from 'node:fs';
import path from 'node:path';
import { MIGRATIONS_DIR, REVIEW_FILE, readWordList, slug } from './shared.mjs';

const FORBIDDEN_COUNT = { easy: 3, medium: 4, hard: 5 };
const ONE_WORD = /^\p{L}+(['’-]\p{L}+)*$/u;
const PHRASE = /^\p{L}+([ '’-]\p{L}+)*$/u;

if (!fs.existsSync(REVIEW_FILE)) {
  console.error(`No review file at ${path.relative(process.cwd(), REVIEW_FILE)}. Run scripts/words/draft.mjs first.`);
  process.exit(1);
}
const reviewed = JSON.parse(fs.readFileSync(REVIEW_FILE, 'utf8'));
const words = new Map(readWordList().map((w) => [slug(w.word), w]));

const problems = [];
const seen = new Set();
for (const e of reviewed) {
  const where = e.word ?? e.id ?? '(no word)';
  const word = words.get(e.id);
  if (!word) { problems.push(`${where}: id "${e.id}" is not in the word list`); continue; }
  if (seen.has(e.id)) problems.push(`${where}: listed twice`);
  seen.add(e.id);
  if (e.check) problems.push(`${where}: still has a check note ("${e.check}")`);
  if (!(e.difficulty in FORBIDDEN_COUNT)) { problems.push(`${where}: difficulty must be easy, medium or hard`); continue; }
  const forbidden = e.forbidden ?? [];
  if (forbidden.length !== FORBIDDEN_COUNT[e.difficulty]) {
    problems.push(`${where}: ${e.difficulty} needs ${FORBIDDEN_COUNT[e.difficulty]} forbidden words, has ${forbidden.length}`);
  }
  for (const f of forbidden) if (!ONE_WORD.test(f)) problems.push(`${where}: forbidden "${f}" is not one word`);
  for (const c of e.components ?? []) if (!ONE_WORD.test(c)) problems.push(`${where}: component "${c}" is not one word`);
  for (const v of e.variants ?? []) if (!PHRASE.test(v)) problems.push(`${where}: variant "${v}" has characters other than letters`);
  const self = [word.word.toLowerCase(), ...(e.components ?? [])];
  for (const f of forbidden) if (self.includes(f.toLowerCase())) problems.push(`${where}: "${f}" is the word or a component, which are blocked anyway`);
}

if (problems.length) {
  console.error(`Not written: ${problems.length} thing(s) to fix in the review file.\n`);
  for (const p of problems) console.error(`  ${p}`);
  process.exit(1);
}

const missing = [...words.keys()].filter((id) => !seen.has(id));
const tiers = { easy: 0, medium: 0, hard: 0 };
for (const id of words.keys()) {
  const e = reviewed.find((r) => r.id === id);
  tiers[e?.difficulty ?? words.get(id).difficulty]++;
}
const short = Object.entries(tiers).filter(([, n]) => n < 30);

const q = (s) => `'${s.toLowerCase().replace(/'/g, "''")}'`;
const arr = (list = []) => (list.length ? `array[${list.map(q).join(', ')}]` : `'{}'::text[]`);
const lines = reviewed.map((e) =>
  `update words set difficulty = '${e.difficulty}', forbidden = ${arr(e.forbidden)}, ` +
  `components = ${arr(e.components)}, variants = ${arr(e.variants)} where id = '${e.id}';`,
);

const last = fs.readdirSync(MIGRATIONS_DIR).filter((f) => /^\d{3}_/.test(f)).sort().at(-1);
const next = String(Number(last.slice(0, 3)) + 1).padStart(3, '0');
const file = path.join(MIGRATIONS_DIR, `${next}_word_cards.sql`);
fs.writeFileSync(
  file,
  `-- Yappa: reviewed word cards (difficulty, forbidden words, components, variants).\n` +
    `-- Generated by scripts/words/to-sql.mjs from the hand-reviewed words.review.json.\n` +
    `-- Pool after this: ${tiers.easy} Easy, ${tiers.medium} Medium, ${tiers.hard} Hard.\n\n` +
    lines.join('\n') + '\n',
);

console.log(`Wrote ${path.relative(process.cwd(), file)}: ${lines.length} words.`);
console.log(`Pool: ${tiers.easy} Easy, ${tiers.medium} Medium, ${tiers.hard} Hard.`);
if (missing.length) {
  const names = missing.length > 12 ? `${missing.slice(0, 12).join(', ')} and ${missing.length - 12} more` : missing.join(', ');
  console.warn(`${missing.length} word(s) not in the review file keep their current difficulty and no lists: ${names}`);
}
if (short.length) console.warn(`Few words in ${short.map(([t, n]) => `${t} (${n})`).join(', ')}: Play Again will repeat words sooner.`);
