// Turns the reviewed clue ladders (scripts/words/review/clue-ladders.json) into
// src/game/soloLadders.ts, the word list solo mode plays from. Run it after the ladders have
// been reviewed: it is what ships to players.
//
// Run: node scripts/words/solo-ladders.mjs
//
// Refuses (and lists why) if a ladder doesn't have 8 different one-word clues, or if a clue
// gives the answer away: the word itself, its plural, a part of it (tooth, brush) or a
// variant (hippo).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REVIEW_FILE } from './shared.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const LADDERS_FILE = path.join(root, 'scripts', 'words', 'review', 'clue-ladders.json');
const OUT_FILE = path.join(root, 'src', 'game', 'soloLadders.ts');
const CLUES = 8;
const LEVELS = ['easy', 'medium', 'hard'];

for (const f of [LADDERS_FILE, REVIEW_FILE]) {
  if (!fs.existsSync(f)) {
    console.error(`Missing ${path.relative(root, f)}.`);
    process.exit(1);
  }
}
const ladders = JSON.parse(fs.readFileSync(LADDERS_FILE, 'utf8'));
const cards = new Map(JSON.parse(fs.readFileSync(REVIEW_FILE, 'utf8')).map((c) => [c.id, c]));

const problems = [];
const out = [];
for (const l of ladders) {
  const card = cards.get(l.id);
  if (!card || card.status === 'cut') {
    problems.push(`${l.word}: not in the word list`);
    continue;
  }
  const clues = l.clues.map((c) => c.trim().toLowerCase());
  if (clues.length !== CLUES) problems.push(`${l.word}: ${clues.length} clues, needs ${CLUES}`);
  if (new Set(clues).size !== clues.length) problems.push(`${l.word}: a clue repeats`);
  const target = card.word.toLowerCase().replace(/[^a-z]/g, '');
  const giveaways = [target, target.replace(/(es|s)$/, ''), ...card.components, ...card.variants]
    .map((g) => g.toLowerCase().replace(/[^a-z]/g, ''))
    .filter((g) => g.length >= 2);
  for (const c of clues) {
    if (!/^[a-z]+$/.test(c)) problems.push(`${l.word}: "${c}" isn't one word`);
    const hit = giveaways.find((g) => c.includes(g));
    if (hit) problems.push(`${l.word}: "${c}" gives it away (${hit})`);
  }
  if (!LEVELS.includes(card.difficulty)) problems.push(`${l.word}: unknown difficulty ${card.difficulty}`);
  out.push({
    id: card.id,
    word: card.word,
    category: card.category,
    difficulty: card.difficulty,
    clues,
    answers: card.variants,
  });
}
for (const c of cards.values()) {
  if (c.status !== 'cut' && !ladders.some((l) => l.id === c.id)) problems.push(`${c.word}: no ladder`);
}
if (problems.length) {
  console.error(`Not written. Fix these first:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

out.sort((a, b) => a.id.localeCompare(b.id));
const body = out.map((w) => `  ${JSON.stringify(w)},`).join('\n');
fs.writeFileSync(
  OUT_FILE,
  `// Generated by scripts/words/solo-ladders.mjs from the reviewed clue ladders. Don't edit by hand:\n` +
    `// change the ladders and run the script again.\nimport type { SoloLadder } from './solo';\n\n` +
    `export const SOLO_LADDERS: readonly SoloLadder[] = [\n${body}\n];\n`,
);
console.log(`Wrote ${out.length} ladders to ${path.relative(root, OUT_FILE)}.`);
